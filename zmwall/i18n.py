TRANSLATIONS: Mapping[str, Mapping[str, str]] = {"de": DE, "en": EN}


def resolve_language(saved: str | None, accept_languages: Any) -> str:
    """Use an explicit preference, otherwise the browser/system preference."""
    if saved in SUPPORTED_LANGUAGES:
        return saved
    return accept_languages.best_match(SUPPORTED_LANGUAGES, default="en") or "en"


def translate(language: str, key: str, **values: Any) -> str:
    text = TRANSLATIONS.get(language, EN).get(key, EN.get(key, key))
    return text.format(**values)
